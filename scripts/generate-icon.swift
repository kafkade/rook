import AppKit
import ImageIO
import UniformTypeIdentifiers

let size = 1024
guard let context = CGContext(
    data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: 0,
    space: CGColorSpaceCreateDeviceRGB(),
    bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue
) else { fatalError("Unable to create the icon renderer.") }
context.setFillColor(CGColor(red: 0.063, green: 0.114, blue: 0.188, alpha: 1))
context.fill(CGRect(x: 0, y: 0, width: size, height: size))
let colors = [
    CGColor(red: 1, green: 0.835, blue: 0.51, alpha: 1),
    CGColor(red: 1, green: 0.835, blue: 0.51, alpha: 1),
    CGColor(red: 0.30, green: 0.40, blue: 0.53, alpha: 1)
]
for index in 0..<3 {
    let rect = CGRect(x: 252 + index * 24, y: 624 - index * 156, width: 470, height: 88)
    context.setFillColor(colors[index])
    context.addPath(CGPath(roundedRect: rect, cornerWidth: 44, cornerHeight: 44, transform: nil))
    context.fillPath()
}
guard let image = context.makeImage() else { fatalError("Unable to render the icon.") }
let recipe = "Original programmatic Rook artwork, not sourced or generated by an image model. "
    + "Opaque 1024x1024 RGB(0.063,0.114,0.188) canvas. Three 470x88 rounded marks, "
    + "radius 44, at x=252+24*i and y=624-156*i in Core Graphics coordinates. "
    + "Marks 0 and 1: RGB(1,0.835,0.51); mark 2: RGB(0.30,0.40,0.53). "
    + "No text, shadows, borders, or external artwork. Source: scripts/generate-icon.swift."
let png = NSMutableData()
guard let destination = CGImageDestinationCreateWithData(png, UTType.png.identifier as CFString, 1, nil) else {
    fatalError("Unable to encode the icon.")
}
CGImageDestinationAddImage(destination, image, [
    kCGImagePropertyPNGDictionary: [kCGImagePropertyPNGDescription: recipe]
] as CFDictionary)
guard CGImageDestinationFinalize(destination) else { fatalError("Unable to finalize the icon.") }
let output = URL(fileURLWithPath: "apple/Rook/Assets.xcassets/AppIcon.appiconset/AppIcon.png")
try (png as Data).write(to: output, options: .atomic)
